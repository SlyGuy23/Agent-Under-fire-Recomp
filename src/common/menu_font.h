struct MenuFont {
    const MenuGlyph* glyphs;
    int count;
    uint8_t space;        // a space's advance
    uint8_t line_height;  // top of a capital to the bottom of a descender, and a little
    const char* key;      // the sheet's texture pack key
};

inline constexpr MenuFont kItalicFont{kItalicGlyphs, int(sizeof(kItalicGlyphs) / sizeof(kItalicGlyphs[0])), 8, 15,
                                      "254f6da069f11c3f"};
inline constexpr MenuFont kListFont{kListGlyphs, int(sizeof(kListGlyphs) / sizeof(kListGlyphs[0])), 7, 17,
                                    "2829182bc4c846c2"};

// the pages: the body in the list's lettering, titles and tabs in the italic one
inline constexpr const MenuFont& kBodyFont = kListFont;
inline constexpr const MenuFont& kTitleFont = kItalicFont;

inline const MenuGlyph* FindGlyph(const MenuFont& f, char c) {
    for (int i = 0; i < f.count; i++)
        if (f.glyphs[i].c == c) return &f.glyphs[i];
    return nullptr;
}

