// Where the letter after a starts (texels after a's start) when b follows it, for this port's own lines in the
// italic lettering: the table's advances are the game's, measured from its own lines, and with letters those lines
// never pair they leave uneven gaps ("Settin gs", "tt" and "et" touching). Here the clear space between the two
// letters' ink, row by row (and a row up or down, the italic slant's diagonal neighbours), is made the same 2 texels
// the game's own rows mostly have, rounded to a whole texel and no more than 3 from the table's advance.
inline int ItalicAdvance(char a, char b) {
    const MenuGlyph* ga = FindGlyph(kItalicFont, a);
    if (!ga) return kItalicFont.space;
    const MenuGlyph* gb = FindGlyph(kItalicFont, b);
    if (!gb) return ga->advance;
    const ItalicInk& ia = kItalicInk[ga - kItalicGlyphs];
    const ItalicInk& ib = kItalicInk[gb - kItalicGlyphs];
    constexpr float kGap = 2.0f;
    float gap = 1e9f;
    for (int r = 0; r < 16; r++) {
        if (ia.r[r] == -128) continue;
        for (int d = -1; d <= 1; d++) {
            int r2 = r + d;
            if (r2 < 0 || r2 >= 16 || ib.l[r2] == -128) continue;
            float g = float(ga->advance) + float(ib.l[r2] - ia.r[r]) / 4.0f + (d != 0 ? 0.3f : 0.0f);
            if (g < gap) gap = g;
        }
    }
    if (gap > 1e8f) return ga->advance;
    float adv = float(ga->advance) - gap + kGap;
    float lo = float(ga->advance) - 3, hi = float(ga->advance) + 3;
    adv = adv < lo ? lo : (adv > hi ? hi : adv);
    return int(adv + (adv >= 0 ? 0.5f : -0.5f));
}

